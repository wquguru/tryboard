static void px(int x, int y, int on)
{
    if (x < 0 || x >= 128 || y < 0 || y >= 64) return;
    if (on) fb[(y / 8) * 128 + x] |= 1 << (y % 8);
    else fb[(y / 8) * 128 + x] &= ~(1 << (y % 8));
}

static void text(int x, int y, const char *s, int scale)
{
    for (; *s; s++, x += 6 * scale) {
        int c = (*s < 0x20 || *s > 0x7e) ? '?' : *s;
        for (int col = 0; col < 5; col++)
            for (int row = 0; row < 7; row++)
                if (font5x7[c - 0x20][col] >> row & 1)
                    for (int dx = 0; dx < scale; dx++)
                        for (int dy = 0; dy < scale; dy++) px(x + col * scale + dx, y + row * scale + dy, 1);
    }
}

static void rect(int x, int y, int w, int h, int fill)
{
    for (int i = x; i < x + w; i++)
        for (int j = y; j < y + h; j++)
            if (fill || i == x || i == x + w - 1 || j == y || j == y + h - 1) px(i, j, 1);
}

static esp_err_t cmds(const uint8_t *c, size_t n)
{
    uint8_t buf[32];
    buf[0] = 0x00; // 控制字节：后面全是命令
    memcpy(buf + 1, c, n);
    return i2c_master_transmit(oled, buf, n + 1, 100);
}

static esp_err_t flush(void)
{
    static const uint8_t win[] = {0x21, 0, 127, 0x22, 0, 7};
    ESP_ERROR_CHECK(cmds(win, sizeof win));
    static uint8_t buf[1 + sizeof fb];
    buf[0] = 0x40; // 控制字节：后面全是显存数据
    memcpy(buf + 1, fb, sizeof fb);
    return i2c_master_transmit(oled, buf, sizeof buf, 200);
}

void app_main(void)
{
    i2c_master_bus_config_t bc = {
        .i2c_port = 0,
        .sda_io_num = PIN_SDA,
        .scl_io_num = PIN_SCL,
        .clk_source = I2C_CLK_SRC_DEFAULT,
        .glitch_ignore_cnt = 7,
        .flags.enable_internal_pullup = true,
    };
    ESP_ERROR_CHECK(i2c_new_master_bus(&bc, &bus));

    printf("I2C scan (SDA=GPIO%d, SCL=GPIO%d):", PIN_SDA, PIN_SCL);
    int found = 0;
    for (int a = 0x08; a < 0x78; a++) {
        if (i2c_master_probe(bus, a, 50) == ESP_OK) {
            printf(" 0x%02X", a);
            found++;
        }
    }
    printf("  (%d device%s)\n", found, found == 1 ? "" : "s");

    i2c_device_config_t dc = {
        .dev_addr_length = I2C_ADDR_BIT_LEN_7,
        .device_address = OLED_ADDR,
        .scl_speed_hz = 400000,
    };
    ESP_ERROR_CHECK(i2c_master_bus_add_device(bus, &dc, &oled));

    // 标准初始化序列：关显示、时钟、复用率、偏移、起始行、电荷泵、水平寻址、段重映射、COM 反扫、对比度、开显示
    static const uint8_t init[] = {0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40, 0x8D, 0x14, 0x20, 0x00,
                                   0xA1, 0xC8, 0xDA, 0x12, 0x81, 0xCF, 0xD9, 0xF1, 0xDB, 0x40, 0xA4, 0xA6, 0xAF};
    ESP_ERROR_CHECK(cmds(init, sizeof init));
    printf("SSD1306 init OK\n");

    for (int t = 0;; t++) {
        memset(fb, 0, sizeof fb);
        rect(0, 0, 128, 64, 0);
        text(16, 5, "TryBoard", 2);
        text(10, 24, CHIP_NAME "+SSD1306", 1);
        text(10, 34, "I2C 0x3C @400kHz", 1);
        // 进度条：每秒前进一格
        rect(10, 46, 108, 10, 0);
        rect(12, 48, 104 * ((t % 10) + 1) / 10, 6, 1);
        int64_t t0 = esp_timer_get_time();
        ESP_ERROR_CHECK(flush());
        int64_t us = esp_timer_get_time() - t0;
        printf("frame %d flushed in %lld us\n", t, (long long)us);
        if (t == 0) printf("TRYBOARD_OK oled\n");
        vTaskDelay(pdMS_TO_TICKS(1000));
    }
}
