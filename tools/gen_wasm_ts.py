#!/usr/bin/env python3
"""R-07: generate web/src/wasm.gen.ts (the wasm export interface) from core/crates/wasm/src/lib.rs.

Usage: tools/gen_wasm_ts.py           rewrite the file
       tools/gen_wasm_ts.py --check   exit 1 if the checked-in file is stale (accept.sh)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "core/crates/wasm/src/lib.rs"
OUT = ROOT / "web/src/wasm.gen.ts"
# Every wasm32 scalar the bindings use maps to a JS number (no i64 / u64 yet: those would be bigint)
NUMBER = {"u8", "u16", "u32", "i32", "usize", "isize", "f32", "f64", "bool"}


def ts_type(rust: str) -> str:
    rust = rust.strip()
    if not rust:
        return "void"
    if rust.startswith("*") or rust in NUMBER:
        return "number"
    raise SystemExit(f"gen_wasm_ts: no TS mapping for Rust type '{rust}' (add one here)")


def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(w.title() for w in rest)


def generate() -> str:
    src = SRC.read_text()
    pat = re.compile(r'((?:[ \t]*///[^\n]*\n)*)#\[no_mangle\]\s*pub (?:unsafe )?extern "C" fn (\w+)\s*\(([^)]*)\)\s*(?:->\s*([^{]+?))?\s*\{', re.S)
    lines = [
        "// Generated by tools/gen_wasm_ts.py from core/crates/wasm/src/lib.rs: do not edit.",
        "// accept.sh fails when this file is stale; rerun the script after changing an export.",
        "",
        "export interface WasmExports {",
        "  memory: WebAssembly.Memory;",
    ]
    n = 0
    for doc, name, args, ret in pat.findall(src):
        docs = [d.strip()[3:].strip() for d in doc.strip().splitlines() if d.strip()]
        if docs:
            lines.append(f"  /** {' '.join(docs).replace('*/', '* /')} */")
        params = ", ".join(f"{camel(p.split(':', 1)[0].strip().lstrip('_'))}: {ts_type(p.split(':', 1)[1])}" for p in args.split(",") if p.strip())
        lines.append(f"  {name}({params}): {ts_type(ret or '')};")
        n += 1
    if n != src.count('extern "C" fn'):
        raise SystemExit(f"gen_wasm_ts: parsed {n} exports but lib.rs has more extern \"C\" fns (signature shape changed?)")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = generate()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"✗ {OUT.relative_to(ROOT)} is stale: run tools/gen_wasm_ts.py")
            sys.exit(1)
        print(f"wasm exports: {len(re.findall(r'^  tb_', text, re.M))} in sync")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT.relative_to(ROOT)} ({len(re.findall(r'^  tb_', text, re.M))} exports)")
